l=[1,2,3,40,12,90,6,7]

#length of the list
print(len(l))

#maximum number from list
print(max(l))

#minimum number from the list
print(min(l))

#sum of list
print(sum(l))

#any() :return true if any one of the item from list is positive
print(any(l))

#all(): returns true if all the functions from list are true 
print(all(l))

#sorted(): sorts the list
print(sorted(l))